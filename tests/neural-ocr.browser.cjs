const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
(async () => {
  const browser = await chromium.launch({channel: 'chrome', headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}, hasTouch: true});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.goto('http://127.0.0.1:8765/games/neural-ocr.html');
    await page.getByRole('button', {name: 'Jeden krok', exact: true}).click({timeout: 3000});
    assert.equal(await page.locator('#steps').textContent(), '1');
    await page.locator('#speed').selectOption('fast');
    await page.getByRole('button', {name: 'Nauč se', exact: true}).click();
    await page.waitForFunction(() => Number(document.querySelector('#epochs').textContent) >= 10);
    await page.getByRole('button', {name: 'Pozastavit', exact: true}).click();
    const paused = await page.locator('#steps').textContent();
    await page.waitForTimeout(200);
    assert.equal(await page.locator('#steps').textContent(), paused);
    await page.getByRole('button', {name: 'Nauč se', exact: true}).click();
    await page.waitForFunction(() => Number(document.querySelector('#epochs').textContent) >= 100);
    await page.waitForTimeout(200);
    assert.equal(await page.locator('#steps').textContent(), '5000', 'training must stop at its fixed budget');
    assert.equal(await page.locator('#train').isDisabled(), true);
    assert.equal(await page.locator('#step').isDisabled(), true);
    assert.match(await page.locator('#status').textContent(), /Dokončeno/);
    assert.ok(parseInt(await page.locator('#accuracy').textContent()) >= 90);
    await page.getByRole('button', {name: 'Číslice 7, varianta 3', exact: true}).click();
    assert.equal(await page.locator('#prediction').textContent(), '7');
    await page.getByRole('button', {name: 'Vymazat kresbu', exact: true}).click();
    assert.equal(await page.locator('#prediction').textContent(), '—');
    await page.locator('#draw').scrollIntoViewIfNeeded();
    const box = await page.locator('#draw').boundingBox();
    const frame = await page.locator('.drawing-wrap').boundingBox();
    assert.ok(frame.width - box.width < 4, 'the visible drawing frame must be drawable across its width');
    await page.mouse.move(box.x + box.width * .5, box.y + box.height * .2);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * .5, box.y + box.height * .8, {steps: 20});
    await page.mouse.up();
    await page.waitForFunction(() => document.querySelector('#prediction').textContent !== '—');
    assert.equal(await page.locator('#input-name').textContent(), 'Tvoje kresba');
    assert.match(await page.locator('#result-source').textContent(), /TVOJE KRESBA/);
    await page.getByRole('button', {name: 'Číslice 7, varianta 3', exact: true}).click();
    assert.match(await page.locator('#result-source').textContent(), /VZOR 7/);
    await page.getByRole('button', {name: 'Začít od nuly', exact: true}).click();
    await page.locator('#draw').scrollIntoViewIfNeeded();
    const held = await page.locator('#draw').boundingBox();
    await page.mouse.move(held.x + 80, held.y + 80);
    await page.mouse.down();
    await page.locator('#train').focus();
    await page.keyboard.press('Enter');
    await page.mouse.move(held.x + 90, held.y + 100);
    await page.mouse.up();
    assert.equal(await page.locator('#train').textContent(), 'Nauč se', 'continuing a stroke must pause training');
    await page.screenshot({path: '/tmp/neural-ocr-desktop.png', fullPage: true});
    await page.getByRole('button', {name: 'Začít od nuly', exact: true}).click();
    assert.equal(await page.locator('#steps').textContent(), '0');
    assert.match(await page.locator('#status').textContent(), /Nenatrénováno/);
    await page.getByRole('button', {name: 'Nauč se', exact: true}).click();
    await page.getByRole('button', {name: 'Začít od nuly', exact: true}).click();
    await page.waitForTimeout(200);
    assert.equal(await page.locator('#steps').textContent(), '0');
    await page.setViewportSize({width: 390, height: 844});
    await page.locator('#draw').scrollIntoViewIfNeeded();
    await page.getByRole('button', {name: 'Vymazat kresbu', exact: true}).click();
    const mobileBox = await page.locator('#draw').boundingBox();
    await page.touchscreen.tap(mobileBox.x + mobileBox.width / 2, mobileBox.y + mobileBox.height / 2);
    await page.waitForFunction(() => document.querySelector('#prediction').textContent !== '—');
    const sampleTarget = await page.getByRole('button', {name: 'Číslice 7, varianta 3', exact: true}).boundingBox();
    assert.ok(sampleTarget.width >= 40 && sampleTarget.height >= 40, 'samples must be usable touch targets');
    await page.screenshot({path: '/tmp/neural-ocr-mobile.png', fullPage: true});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.goto('http://127.0.0.1:8765/');
    await page.getByRole('link', {name: /Neuronová laboratoř/}).waitFor();
    await page.screenshot({path: '/tmp/neural-ocr-home.png', fullPage: true});
    assert.deepEqual(errors, []);
    console.log('Browser checks passed: training, pause, step, sample, drawing, clear, reset, mobile, no JS errors.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
